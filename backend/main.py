from fastapi import FastAPI
from routes.gym import router as gym_router

app = FastAPI()
app.include_router(gym_router)


@app.get("/")
def read_root():
    return {"Hello": "World"}


@app.get("/items/{item_id}")
def read_item(item_id: int, q: str | None = None):
    return {"item_id": item_id, "q": q}
